"use client";

import { useState, useRef, useEffect } from "react";
import { Download, FileText, File, ChevronDown } from "lucide-react";

interface ExportRoadmapButtonProps {
  studentName: string;
  studentEmail: string;
  date: string;
}

export function ExportRoadmapButton({ studentName, studentEmail, date }: ExportRoadmapButtonProps) {
  const [isOpen, setIsOpen] = useState(false);
  const dropdownRef = useRef<HTMLDivElement>(null);

  // Close dropdown on click outside
  useEffect(() => {
    function handleClickOutside(event: MouseEvent) {
      if (dropdownRef.current && !dropdownRef.current.contains(event.target as Node)) {
        setIsOpen(false);
      }
    }
    document.addEventListener("mousedown", handleClickOutside);
    return () => document.removeEventListener("mousedown", handleClickOutside);
  }, []);

  const exportAsPDF = () => {
    setIsOpen(false);
    // Add a class to body for print-specific styles if needed, then print
    window.print();
  };

  const exportAsWord = () => {
    setIsOpen(false);
    
    // Get the HTML content of the roadmap container.
    const contentElement = document.getElementById("roadmap-content");
    
    if (!contentElement) {
      alert("Could not find the roadmap content to export.");
      return;
    }

    // Clone the element to remove non-exportable items like buttons
    const clone = contentElement.cloneNode(true) as HTMLElement;
    
    // Remove export button or other interactive elements from the clone if they exist inside
    const nonExportable = clone.querySelectorAll('.no-export, .pdf-cover');
    nonExportable.forEach(el => el.parentNode?.removeChild(el));

    // Cover Page for Word Document
    const wordCover = `
      <div style="text-align: center; margin-bottom: 40px; padding-bottom: 20px; border-bottom: 2px solid #1D4ED8;">
        <h1 style="color: #0B1F3A; font-size: 26pt; font-weight: bold; margin-bottom: 10px;">Personalized Study-Abroad Report</h1>
        <p style="color: #64748B; font-size: 14pt;">Generated by K-GEO &amp; Gemini AI</p>
      </div>
      <table style="width: 100%; margin-bottom: 40px; font-family: 'Segoe UI', Arial, sans-serif; border-collapse: collapse;">
        <tr>
          <td style="padding: 12px; border-bottom: 1px solid #E2E8F0; width: 50%;">
            <strong style="color: #64748B; font-size: 10pt; text-transform: uppercase;">Student Name</strong><br/>
            <span style="font-size: 14pt; color: #0F172A; font-weight: bold;">${studentName}</span>
          </td>
          <td style="padding: 12px; border-bottom: 1px solid #E2E8F0; width: 50%;">
            <strong style="color: #64748B; font-size: 10pt; text-transform: uppercase;">College Email</strong><br/>
            <span style="font-size: 14pt; color: #0F172A; font-weight: bold;">${studentEmail}</span>
          </td>
        </tr>
        <tr>
          <td colspan="2" style="padding: 12px; border-bottom: 1px solid #E2E8F0;">
            <strong style="color: #64748B; font-size: 10pt; text-transform: uppercase;">Report Generated</strong><br/>
            <span style="font-size: 14pt; color: #0F172A; font-weight: bold;">${date}</span>
          </td>
        </tr>
      </table>
      <br clear="all" style="page-break-before:always" />
    `;

    // Basic styles for Word doc mapping
    const styles = `
      <style>
        body { font-family: 'Segoe UI', Arial, sans-serif; color: #0F172A; }
        h1 { color: #0B1F3A; font-size: 24pt; }
        h2 { color: #0B1F3A; font-size: 18pt; margin-top: 20px; border-bottom: 1px solid #DCE6F2; padding-bottom: 5px; }
        h3 { color: #0B1F3A; font-size: 14pt; }
        .bucket-tag { font-weight: bold; padding: 4px; background-color: #f1f5f9; border: 1px solid #cbd5e1; border-radius: 4px; }
        .card { border: 1px solid #DCE6F2; padding: 15px; margin-bottom: 15px; border-radius: 8px; }
        .course { color: #1D4ED8; font-weight: bold; }
        .tip { font-size: 10pt; color: #64748B; font-style: italic; }
      </style>
    `;

    // Create a basic HTML structure for MS Word
    const header = "<html xmlns:o='urn:schemas-microsoft-com:office:office' " +
      "xmlns:w='urn:schemas-microsoft-com:office:word' " +
      "xmlns='http://www.w3.org/TR/REC-html40'>" +
      "<head><meta charset='utf-8'><title>Personalized Roadmap</title>" + styles + "</head><body>";
    const footer = "</body></html>";
    const sourceHTML = header + wordCover + clone.innerHTML + footer;
    
    // Create a Blob with the file contents
    const blob = new Blob(['\ufeff', sourceHTML], {
      type: 'application/msword'
    });
    
    // Specify link url
    const url = 'data:application/vnd.ms-word;charset=utf-8,' + encodeURIComponent(sourceHTML);
    
    // Create download link element
    const downloadLink = document.createElement("a");
    document.body.appendChild(downloadLink);
    
    interface MSNavigator extends Navigator {
      msSaveOrOpenBlob?: (blob: Blob, defaultName?: string) => boolean;
    }

    const msNav = navigator as MSNavigator;

    if (msNav.msSaveOrOpenBlob) {
      // IE11
      msNav.msSaveOrOpenBlob(blob, 'K-GEO_Roadmap.doc');
    } else {
      // Other browsers
      downloadLink.href = url;
      downloadLink.download = 'K-GEO_Roadmap.doc';
      downloadLink.click();
    }
    
    document.body.removeChild(downloadLink);
  };

  return (
    <div className="relative no-export" ref={dropdownRef}>
      <button
        onClick={() => setIsOpen(!isOpen)}
        className="flex items-center gap-2 px-4 py-2 rounded-lg border border-[#DCE6F2] bg-white text-[#0F172A] text-sm font-medium hover:bg-gray-50 transition-colors shadow-sm"
        aria-label="Export roadmap options"
      >
        <Download className="w-4 h-4" />
        Export
        <ChevronDown className={`w-4 h-4 transition-transform ${isOpen ? "rotate-180" : ""}`} />
      </button>

      {isOpen && (
        <div className="absolute right-0 mt-2 w-48 bg-white border border-[#DCE6F2] rounded-xl shadow-lg z-50 overflow-hidden animate-in fade-in slide-in-from-top-2 duration-200">
          <button
            onClick={exportAsPDF}
            className="w-full flex items-center gap-3 px-4 py-3 text-sm text-[#0F172A] hover:bg-gray-50 transition-colors text-left border-b border-gray-100"
          >
            <FileText className="w-4 h-4 text-red-500" />
            <div className="flex flex-col">
              <span className="font-medium">Export as PDF</span>
              <span className="text-[10px] text-[#64748B]">Via Print Dialog</span>
            </div>
          </button>
          <button
            onClick={exportAsWord}
            className="w-full flex items-center gap-3 px-4 py-3 text-sm text-[#0F172A] hover:bg-gray-50 transition-colors text-left"
          >
            <File className="w-4 h-4 text-blue-500" />
            <div className="flex flex-col">
              <span className="font-medium">Export as Word</span>
              <span className="text-[10px] text-[#64748B]">Download .doc</span>
            </div>
          </button>
        </div>
      )}
    </div>
  );
}
